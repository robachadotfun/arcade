/**
 * The Arcade reward registry.
 *
 * ## Where this data comes from
 *
 * Every address here was verified against Arc Mainnet by `scripts/verify-arc-tokens.ts`,
 * which reads `name`/`symbol`/`decimals`/`totalSupply` straight from the contract and then
 * executes `transfer` against live state through an `eth_call` state override to confirm the
 * full amount actually arrives. Tokens that fail any check are recorded with their reasons
 * and never reach this file.
 *
 * No address in Arcade is hand-written. If a token is not in the verification report, it
 * cannot be a reward.
 *
 * ## Why nothing here is a "top token" ranking
 *
 * Arc mainnet opened on 2026-09-16. Rankings will churn for months. This module exposes a
 * *configurable registry* — enable, disable, pause, re-tier, set inventory — and the
 * ordering you see in the UI comes from live registry state onchain, not from a list baked
 * into the bundle. The seeds below exist so a fresh checkout has something coherent to show.
 *
 * ## What "Verified by Arcade" means
 *
 * That we checked the token *contract*: right address, honest decimals, transfers that do
 * not skim. It is not a judgement about the asset, its price, or its prospects, and it is
 * not an endorsement by anyone.
 */

export type RewardTier = 'featured' | 'verified' | 'discovery' | 'paused'

export type RewardAsset = {
  address: `0x${string}`
  /** The symbol the contract reports. The registry asserts this on-chain; never override it. */
  symbol: string
  /**
   * What players are shown instead of {@link symbol}, when the real ticker would mislead.
   *
   * Only set for admitted ticker collisions — see {@link ADMITTED_COLLISIONS}. Everywhere a
   * reward is displayed, use {@link labelFor} rather than `symbol`.
   */
  displaySymbol?: string
  /** Why this asset carries a display override, shown next to it in the UI. */
  collisionNote?: string
  name: string
  decimals: number
  tier: RewardTier
  /** True only when the live transfer probe moved the full amount and returned true. */
  transferVerified: boolean
  /** Point-in-time third-party snapshot. Never used for solvency maths. */
  snapshot: {
    liquidityUsd: number
    volume24hUsd: number
    holders: number
    ageDays: number
    source: string
    capturedAt: string
  }
  /** The project's real published logo. Absent when none exists; never generated by us. */
  logoUri?: string
  /** When there is no logo, why — so a monogram reads as a finding, not an oversight. */
  logoNote?: string
  /** Short editorial note shown in the reward drawer. */
  note?: string
}

type VerifiedToken = (typeof verified)['tokens'][number]

/**
 * Real published logos, keyed by contract address.
 *
 * Built by `scripts/fetch-token-logos.ts`, which downloads each project's actual mark and
 * records where it came from. A token with no published logo is deliberately absent here and
 * falls back to a typographic monogram — Arcade never draws or approximates someone else's
 * logo, because on a chain with six ticker collisions a plausible fake mark is a direct route
 * to confusing two different assets.
 *
 * Keyed by address, never by ticker, for the same reason.
 */
const LOGO_BY_ADDRESS: Record<string, string> = Object.fromEntries(
  logoManifest.logos
    .filter((entry): entry is typeof entry & {file: string} => typeof entry.file === 'string')
    .map((entry) => [entry.address.toLowerCase(), `/tokens/${entry.file}`]),
)

/** Why a given token shows a monogram instead of a logo, for the reward drawer. */
const LOGO_NOTE_BY_ADDRESS: Record<string, string> = Object.fromEntries(
  logoManifest.logos
    .filter((entry) => entry.file === null && typeof entry.note === 'string')
    .map((entry) => [entry.address.toLowerCase(), entry.note as string]),
)

